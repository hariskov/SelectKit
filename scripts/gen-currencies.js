// Generates lib/currency-data.js from Unicode CLDR, as shipped in Node's Intl.
// Run with `npm run gen:currencies` and commit the result.
//
// Produces:
//   CURRENCY_CODES   current ISO 4217 codes
//   CURRENCY_SYMBOLS symbol -> codes that use it (ambiguous when > 1),
//                    including local forms like "US$", "Nkr" or "лв."

const fs = require("node:fs");
const path = require("node:path");

const names = new Intl.DisplayNames(["en"], { type: "currency" });
// Historical currencies have a date range in their name.
const codes = Intl.supportedValuesOf("currency").filter((c) => !names.of(c).includes("("));

// One locale per country, covering every currency symbol in common use.
const LOCALES = [
  "en-US", "en-CA", "fr-CA", "en-AU", "en-NZ", "en-GB", "en-IE", "en-IN", "en-SG", "en-HK", "zh-HK",
  "en-ZA", "en-NG", "en-KE", "en-PH", "en-JM", "en-TT", "en-BB", "en-BS", "en-BZ", "en-FJ", "en-GY",
  "en-LR", "en-NA", "en-SB", "en-BM", "en-KY", "es-MX", "es-AR", "es-CL", "es-CO", "es-UY", "es-DO",
  "es-CU", "es-ES", "es-PE", "es-BO", "es-PY", "es-VE", "es-CR", "es-GT", "es-HN", "es-NI", "pt-BR",
  "pt-PT", "fr-FR", "fr-CH", "de-DE", "de-CH", "de-AT", "it-IT", "nl-NL", "sv-SE", "nb-NO", "da-DK",
  "is-IS", "fi-FI", "pl-PL", "cs-CZ", "sk-SK", "hu-HU", "ro-RO", "ro-MD", "bg-BG", "sr-RS", "mk-MK",
  "hr-HR", "bs-BA", "sq-AL", "el-GR", "tr-TR", "uk-UA", "ru-RU", "be-BY", "ka-GE", "hy-AM", "az-AZ",
  "kk-KZ", "uz-UZ", "he-IL", "ar-EG", "ar-SA", "ar-AE", "ar-MA", "fa-IR", "ur-PK", "hi-IN", "bn-BD",
  "si-LK", "ne-NP", "th-TH", "vi-VN", "id-ID", "ms-MY", "fil-PH", "ja-JP", "zh-CN", "zh-TW", "ko-KR",
  "mn-MN", "km-KH", "lo-LA", "my-MM", "sw-KE", "am-ET", "en-MU", "en-SC",
];

// Symbols that are also ordinary words, units or abbreviations, which would
// turn "5 L" (litres) or "5 KM" into prices: single letters and a few more.
const TOO_GENERIC = new Set(["KM", "kn", "Ar", "Br", "Bs", "Db", "CF", "Cf", "Cg", "Cg.", "FG", "UM", "RF"]);
const usable = (s) => !!s && !/^[A-Z]{3}$/.test(s) && !TOO_GENERIC.has(s) && !/^[A-Za-z]$/.test(s);

function symbolOf(code, locale, display) {
  try {
    const parts = new Intl.NumberFormat(locale, { style: "currency", currency: code, currencyDisplay: display })
      .formatToParts(1);
    return parts.find((p) => p.type === "currency").value.trim();
  } catch {
    return null;
  }
}

// symbol -> Set(code)
const symbols = new Map();
function add(symbol, code) {
  if (!usable(symbol)) return;
  if (!symbols.has(symbol)) symbols.set(symbol, new Set());
  symbols.get(symbol).add(code);
}

for (const code of codes) {
  add(symbolOf(code, "en", "symbol"), code);
  add(symbolOf(code, "en", "narrowSymbol"), code);
}

// How each country writes currencies: "US$" in en-CA, "Nkr" in sv-SE,
// "лв." in bg-BG.
for (const locale of LOCALES) {
  for (const code of codes) add(symbolOf(code, locale, "symbol"), code);
}

// lib/currencies.js looks symbols up case-insensitively.
const byLowerCase = new Map();
for (const symbol of symbols.keys()) {
  const other = byLowerCase.get(symbol.toLowerCase());
  if (other) throw new Error(`"${symbol}" and "${other}" differ only in case`);
  byLowerCase.set(symbol.toLowerCase(), symbol);
}

const sortedSymbols = Object.fromEntries(
  [...symbols.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([symbol, set]) => [symbol, [...set].sort()]),
);

const out = `// Generated by scripts/gen-currencies.js from Unicode CLDR (Node ${process.versions.node},
// ICU ${process.versions.icu}, CLDR ${process.versions.cldr}). Don't edit by hand:
// run \`npm run gen:currencies\`.

const CURRENCY_CODES = ${JSON.stringify(codes)};

const CURRENCY_SYMBOLS = ${JSON.stringify(sortedSymbols, null, 2)};
`;

fs.writeFileSync(path.join(__dirname, "..", "lib", "currency-data.js"), out);
console.log(`${codes.length} currencies, ${Object.keys(sortedSymbols).length} symbols`);
